// Состояние приложения
let currentDay = "pn";
let currentWeek = "верх"; // 'верх' или 'низ'
let selectedSubgroup = "all"; // 'all', '1', '2'

// Получение названия дня
function getDayName(dayCode) {
  const days = {
    pn: "Понедельник",
    vt: "Вторник",
    sr: "Среда",
    cht: "Четверг",
    pt: "Пятница",
    sb: "Суббота"
  };
  return days[dayCode] || dayCode;
}

// Рендер одного занятия
function renderLesson(lesson, weekType) {
  const [time, title, place, teacher, subgroups] = lesson;
  
  // Проверяем, нужно ли показывать для выбранной подгруппы
  if (selectedSubgroup !== "all" && !subgroups.includes(parseInt(selectedSubgroup))) {
    return "";
  }
  
  return `
    <div class="lesson">
      <div class="bar ${weekType === 'верх' ? 'upper-week' : 'lower-week'}"></div>
      <div class="lesson-content">
        <div class="time">
          ${time}
          <span class="week-badge">${weekType === 'верх' ? 'Верхняя неделя' : 'Нижняя неделя'}</span>
          ${subgroups.length === 1 ? `<span class="subgroup-badge">Подгруппа ${subgroups[0]}</span>` : ''}
        </div>
        <div class="title">${title}</div>
        <div class="info">
          ${place ? `<span>📍 ${place}</span>` : ''}
          ${teacher ? `<span>👨‍🏫 ${teacher}</span>` : ''}
        </div>
      </div>
    </div>
  `;
}

// Рендер дня - ТОЛЬКО ВЫБРАННАЯ НЕДЕЛЯ!
function renderDay(day) {
  currentDay = day;
  const box = document.getElementById("schedule");
  const dayData = schedule[day];
  
  if (!dayData) {
    box.innerHTML = `<div class="no-lessons">Нет данных для этого дня</div>`;
    return;
  }
  
  // Получаем занятия ТОЛЬКО для текущей недели
  const currentWeekLessons = dayData[currentWeek] || [];
  
  let html = `
    <div class="day-header">
      <h2>${getDayName(day)}</h2>
      <div class="week-indicator-small">${currentWeek === 'верх' ? 'Верхняя неделя' : 'Нижняя неделя'}</div>
    </div>
  `;
  
  if (currentWeekLessons.length === 0) {
    html += `<div class="no-lessons">На этой неделе нет занятий</div>`;
  } else {
    // Фильтруем по подгруппе
    const filteredLessons = currentWeekLessons.filter(lesson => {
      if (selectedSubgroup === "all") return true;
      return lesson[4].includes(parseInt(selectedSubgroup));
    });
    
    if (filteredLessons.length === 0) {
      html += `<div class="no-lessons">Нет занятий для ${selectedSubgroup === 'all' ? 'всех подгрупп' : 'подгруппы ' + selectedSubgroup}</div>`;
    } else {
      // Сортируем занятия по времени
      filteredLessons.sort((a, b) => {
        const timeA = a[0].split('–')[0].replace(':', '');
        const timeB = b[0].split('–')[0].replace(':', '');
        return parseInt(timeA) - parseInt(timeB);
      });
      
      html += filteredLessons.map(lesson => renderLesson(lesson, currentWeek)).join("");
    }
  }
  
  box.innerHTML = html;
  updateActiveDayButton();
}

// Обновление активной кнопки дня
function updateActiveDayButton() {
  document.querySelectorAll(".day-nav button").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.day === currentDay);
  });
}

// Переключение недели - ТЕПЕРЬ РАБОТАЕТ!
function toggleWeek() {
  currentWeek = currentWeek === "верх" ? "низ" : "верх";
  document.getElementById("currentWeek").textContent = 
    currentWeek === "верх" ? "Верхняя неделя" : "Нижняя неделя";
  
  // Перерисовываем день с новой неделей
  renderDay(currentDay);
}

// Обработчик выбора подгруппы
function handleSubgroupChange(subgroup) {
  selectedSubgroup = subgroup;
  renderDay(currentDay);
}

// Инициализация
document.addEventListener("DOMContentLoaded", () => {
  // Навешиваем клики на дни
  document.querySelectorAll(".day-nav button").forEach(btn => {
    btn.addEventListener("click", () => {
      renderDay(btn.dataset.day);
    });
  });
  
  // Кнопка переключения недели
  document.getElementById("toggleWeek").addEventListener("click", toggleWeek);
  
  // Выбор подгруппы
  document.getElementById("subgroupSelect").addEventListener("change", (e) => {
    handleSubgroupChange(e.target.value);
  });
  
  // Автоматическое определение текущей недели
  function getCurrentWeek() {
    const today = new Date();
    // Простая логика: чётные недели года - нижняя, нечётные - верхняя
    const weekNumber = Math.floor((today.getDate() - 1) / 7) + 1;
    return weekNumber % 2 === 0 ? "низ" : "верх";
  }
  
  currentWeek = getCurrentWeek();
  document.getElementById("currentWeek").textContent = 
    currentWeek === "верх" ? "Верхняя неделя" : "Нижняя неделя";
  
  // Автоматический выбор сегодняшнего дня
  function autoSelectDay() {
    const days = ["pn", "vt", "sr", "cht", "pt", "sb"];
    const today = new Date().getDay(); // 0=воскресенье, 1=понедельник...
    
    const adjustedDay = today === 0 ? 6 : today - 1;
    
    if (adjustedDay < 6 && schedule[days[adjustedDay]]) {
      currentDay = days[adjustedDay];
      updateActiveDayButton();
    }
  }
  
  // Запускаем
  autoSelectDay();
  renderDay(currentDay);
});